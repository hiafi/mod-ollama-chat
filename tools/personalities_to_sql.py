#!/usr/bin/env python3
"""Turn a personalities TOML file into an idempotent SQL file for mod_ollama_chat_personality_templates.

    personalities_to_sql.py personalities.toml --out data/sql/characters/<name>.sql [--source-note "text"]

The file is one multi-row ``REPLACE INTO``, sorted by key, with no DELETE: a key missing from the
TOML keeps whatever row it has in the database. To retire a personality, mark it ``manual_only``.
The input format is the one run_eval.py reads (see eval/README.md).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "eval"))

from personalities import Personalities, load_personalities   # noqa: E402

KEY_RE = re.compile(r"^[A-Z][A-Z0-9_]{0,63}$")    # the `key` column is VARCHAR(64)
TABLE = "mod_ollama_chat_personality_templates"


def sql_string(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


def validate(personalities: Personalities) -> None:
    for key, (prompt, _manual) in personalities.items():
        if not KEY_RE.match(key):
            raise ValueError(f"personality '{key}': key must match ^[A-Z][A-Z0-9_]{{0,63}}$")
        bad = next((c for c in prompt if ord(c) < 0x20 or ord(c) == 0x7F), None)
        if bad is not None:
            raise ValueError(f"personality '{key}': prompt contains control character U+{ord(bad):04X}")
        if not prompt.strip():
            raise ValueError(f"personality '{key}': prompt is empty")
        if '"' in prompt:
            raise ValueError(f"personality '{key}': prompt contains '\"' (not allowed anywhere in this "
                             f"module's config tooling)")


def to_sql(personalities: Personalities, source: str, note: str = "") -> str:
    validate(personalities)
    if not personalities:
        raise ValueError("no personalities to write")
    lines = [f"-- Generated by tools/personalities_to_sql.py from {source}. Do not edit by hand.",
             "-- Idempotent: one REPLACE per `key`. Rows not listed here are left alone (nothing is removed);",
             "-- to retire a personality, mark it manual_only."]
    if note:
        lines += ["-- " + n for n in note.splitlines() if n.strip()]
    lines.append(f"REPLACE INTO `{TABLE}` (`key`, `prompt`, `manual_only`) VALUES")
    rows = [f"({sql_string(k)}, {sql_string(personalities[k][0])}, {1 if personalities[k][1] else 0})"
            for k in sorted(personalities)]
    lines.append(",\n".join(rows) + ";")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("personalities", type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--source-note", default="")
    args = ap.parse_args(argv)
    try:
        sql = to_sql(load_personalities(args.personalities), args.personalities.name, args.source_note)
    except (ValueError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    args.out.write_text(sql, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
